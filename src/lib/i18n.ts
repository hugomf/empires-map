const DICCIONARIOS: Record<Idioma, Diccionario> = { en: EN, es: ES };

export function traducir(idioma: Idioma, clave: string, vars?: Record<string, string | number>): string {
  let txt = DICCIONARIOS[idioma][clave] ?? DICCIONARIOS.en[clave] ?? clave;
  if (vars) for (const [k, v] of Object.entries(vars)) txt = txt.replace(`{${k}}`, String(v));
  return txt;
}

/** El idioma por defecto es el inglés; se recuerda en el navegador. */
export function idiomaGuardado(): Idioma {
  if (typeof localStorage === 'undefined') return 'en';
  const v = localStorage.getItem('cronica-idioma');
  return v === 'es' || v === 'en' ? v : 'en';
}
