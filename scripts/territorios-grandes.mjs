let anadidas = 0;
const omitidas = [];

for (const [civ, t] of POLIGONOS) {
  if (conTerritorio.has(civ)) {
    omitidas.push(civ);
    continue;
  }
  if (!civilizaciones.some((c) => c.id === civ)) {
    omitidas.push(`${civ} (no existe)`);
    continue;
  }
  const id = `${civ}-t${territorios.filter((x) => x.civilizacion === civ).length + 1}`;
  territorios.push({
    id,
    civilizacion: civ,
    tipo: 'tierra',
    nombre: t.nombre,
    ancla: t.ancla,
    desde: t.desde,
    hasta: t.hasta,
    anillos: t.anillos,
    nivel: 'polidad',
    superior: null,
  });
  conTerritorio.add(civ);
  anadidas++;
}

escribir('territorios.json', territorios);

const conT = new Set(territorios.map((t) => t.civilizacion));
